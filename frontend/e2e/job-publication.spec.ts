import { test, expect } from "@playwright/test";
import AxeBuilder from "@axe-core/playwright";
import { mkdirSync } from "node:fs";

test("job draft, publication, withdrawal and archive work on desktop and mobile", async ({ page, request, baseURL }) => {
  test.setTimeout(180_000);
  if (!baseURL || !["localhost", "127.0.0.1"].includes(new URL(baseURL).hostname)) throw new Error("Local synthetic tests only");
  const api = "http://localhost:8001";
  const marker = Date.now();
  const email = `publication-${marker}@example.com`;
  const password = "SyntheticOnly123!";
  // API setup: isolated synthetic account and company. All job changes use visible UI.
  const registration = await request.post(`${api}/auth/register`, { data: { email, password, full_name: "Publication QA" } });
  expect(registration.ok(), await registration.text()).toBeTruthy();
  const headers = { Authorization: `Bearer ${(await registration.json()).access_token}` };
  const company = await request.post(`${api}/companies/`, { headers, data: { name: `Publication ${marker}`, workspace_type: "internal_hr" } });
  expect(company.ok(), await company.text()).toBeTruthy();
  const branding = await request.get(`${api}/companies/workspace/branding`, { headers });
  const slug = (await branding.json()).slug;
  const errors: string[] = [];
  page.on("pageerror", error => errors.push(error.message));
  await page.goto("/login");
  await page.getByLabel("E-Mail").fill(email);
  await page.getByLabel("Passwort", { exact: true }).fill(password);
  await page.getByRole("button", { name: "Anmelden", exact: true }).click();
  await expect(page).not.toHaveURL(/\/login$/);
  await page.goto("/dashboard/jobs/new");
  await page.getByLabel("Stellenbezeichnung").fill(`Publication Engineer ${marker}`);
  await page.getByLabel("Unternehmen", { exact: false }).fill(`Publication ${marker}`);
  await page.getByLabel("Standort", { exact: true }).fill("Berlin");
  await page.getByLabel("Beschäftigungsart").selectOption("full-time");
  await page.getByLabel("Stellenbeschreibung", { exact: true }).fill("Wir suchen Unterstützung für die Qualitätssicherung unserer Software. Aufgaben: Tests planen, Fehler dokumentieren und Ergebnisse gemeinsam prüfen.");
  await page.getByRole("button", { name: "Entwurf speichern", exact: true }).click();
  await expect(page).toHaveURL(/\/dashboard\/jobs$/);
  const job = page.locator('[data-slot="card"]').filter({ has: page.getByRole("heading", { name: `Publication Engineer ${marker}`, exact: true }) });
  await expect(job.getByText("Entwurf", { exact: true })).toBeVisible();
  await expect(job.getByRole("button", { name: "Teilen", exact: true })).toBeDisabled();
  expect((await request.get(`${api}/public/jobs?slug=${slug}`)).ok()).toBeTruthy();
  expect(await (await request.get(`${api}/public/jobs?slug=${slug}`)).json()).toEqual([]);
  await job.getByRole("button", { name: "Veröffentlichung prüfen", exact: true }).click();
  await job.getByRole("checkbox").check();
  await job.getByRole("button", { name: "Jetzt veröffentlichen", exact: true }).click();
  await expect(job.getByText("Veröffentlicht", { exact: true })).toBeVisible();
  await page.reload();
  await expect(job.getByText("Veröffentlicht", { exact: true })).toBeVisible();
  const publicJobs = await (await request.get(`${api}/public/jobs?slug=${slug}`)).json();
  expect(publicJobs).toHaveLength(1);
  const publicPage = await page.context().newPage();
  await publicPage.goto(`/whitelabel/${slug}/jobs/${publicJobs[0].id}`);
  await expect(publicPage.getByRole("heading", { name: `Publication Engineer ${marker}` })).toBeVisible();
  await publicPage.close();
  const captures = "/tmp/hireos-browser-tests/palmscout-publication";
  mkdirSync(captures, { recursive: true });
  await job.scrollIntoViewIfNeeded();
  await page.screenshot({ path: `${captures}/published-desktop.png` });
  await page.setViewportSize({ width: 390, height: 844 });
  await job.getByRole("button", { name: "Zurückziehen", exact: true }).click();
  await job.getByRole("button", { name: "Jetzt zurückziehen", exact: true }).click();
  await expect(job.getByText("Entwurf", { exact: true })).toBeVisible();
  expect((await request.get(`${api}/public/jobs/${publicJobs[0].id}?slug=${slug}`)).status()).toBe(404);
  await job.getByRole("button", { name: "Archivieren", exact: true }).click();
  await job.getByRole("button", { name: "Archivierung bestätigen", exact: true }).click();
  await expect(job.getByText("Archiviert", { exact: true })).toBeVisible();
  await job.getByRole("button", { name: "Verlauf", exact: true }).click();
  await expect(job.getByRole("list", { name: "Veröffentlichungsverlauf" })).toContainText("Zurückgezogen");
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390);
  const a11y = await new AxeBuilder({ page }).withTags(["wcag2a", "wcag2aa", "wcag21aa"]).analyze();
  expect(a11y.violations.filter(item => ["critical", "serious"].includes(item.impact ?? ""))).toEqual([]);
  await job.scrollIntoViewIfNeeded();
  await page.screenshot({ path: `${captures}/archived-mobile.png` });
  await page.reload();
  await expect(job.getByText("Archiviert", { exact: true })).toBeVisible();
  expect(errors).toEqual([]);
});
