import { test, expect } from "@playwright/test";
import AxeBuilder from "@axe-core/playwright";

test.beforeEach(async ({ baseURL }) => {
  if (!baseURL || !["localhost", "127.0.0.1"].includes(new URL(baseURL).hostname)) throw new Error("Local synthetic tests only");
});

test("owner invites a colleague, revokes another link and the colleague joins", async ({ page, browser }) => {
  test.setTimeout(120_000);
  const marker = Date.now();
  const invitedEmail = `join-${marker}@example.com`;
  const errors: string[] = [];
  page.on("pageerror", error => errors.push(error.message));
  await page.goto("/register/recruiter");
  await page.getByLabel("Name", { exact: true }).fill("Workspace Owner");
  await page.getByLabel("E-Mail", { exact: true }).fill(`owner-${marker}@example.com`);
  await page.getByLabel("Passwort", { exact: true }).fill("SyntheticOnly123!");
  await page.getByRole("checkbox").check();
  await page.getByRole("button", { name: "Weiter" }).click();
  await page.getByLabel("Wie arbeitet dein Team?").selectOption("internal_hr");
  await page.getByLabel("Unternehmensname", { exact: false }).fill(`Workspace ${marker}`);
  await page.getByRole("checkbox").check();
  await page.locator('form button[type="submit"]').click();
  await expect(page.getByRole("heading", { name: "Heute", exact: true })).toBeVisible();
  await page.goto("/dashboard/members");
  await page.getByLabel("E-Mail-Adresse", { exact: true }).fill(invitedEmail);
  await page.getByRole("button", { name: "Einladungslink erstellen" }).click();
  const link = page.getByLabel("Einladungslink", { exact: true });
  await expect(link).toBeVisible();
  const invitation = await link.inputValue();
  await page.reload();
  await expect(page.getByText(invitedEmail, { exact: true })).toBeVisible();
  await page.getByLabel("E-Mail-Adresse", { exact: true }).fill(`revoked-${marker}@example.com`);
  await page.getByRole("button", { name: "Einladungslink erstellen" }).click();
  const row = page.getByRole("listitem").filter({ hasText: `revoked-${marker}@example.com` });
  await row.getByRole("button", { name: "Widerrufen", exact: true }).click();
  await expect(row.getByText("Widerrufen", { exact: true })).toBeVisible();
  const context = await browser.newContext();
  const colleague = await context.newPage();
  await colleague.goto(invitation);
  await colleague.getByRole("button", { name: "Noch kein Konto? Registrieren" }).click();
  await colleague.getByLabel("Name", { exact: true }).fill("Invited Colleague");
  await colleague.getByLabel("E-Mail-Adresse", { exact: true }).fill(invitedEmail);
  await colleague.getByLabel("Passwort", { exact: true }).fill("SyntheticOnly123!");
  await colleague.getByRole("button", { name: "Konto erstellen", exact: true }).click();
  await colleague.getByRole("button", { name: "Einladung annehmen", exact: true }).click();
  await expect(colleague).toHaveURL(/\/dashboard$/);
  await expect(colleague.getByRole("heading", { name: "Heute", exact: true })).toBeVisible();
  await page.reload();
  await expect(page.getByText("Invited Colleague", { exact: true })).toBeVisible();
  await page.screenshot({ path: "../.artifacts/browser/workspace-members.png", fullPage: true });
  await context.close();
  expect(errors).toEqual([]);
});

test("today, person record, saved search and command navigation work on desktop and mobile", async ({ page, request }) => {
  test.setTimeout(120_000);
  // API setup only: synthetic worker in the seeded local HR tenant.
  const authResponse = await request.post("http://localhost:8001/auth/login", { form: { username: "recruiter@demo-enterprise.de", password: "Recruiter1234!" } });
  const token = (await authResponse.json()).access_token;
  const marker = Date.now();
  const registration = await request.post("http://localhost:8001/auth/register", { data: { email: `person-${marker}@example.com`, full_name: `Person ${marker}`, password: "SyntheticOnly123!" } });
  expect(registration.ok()).toBeTruthy();
  const candidateToken = (await registration.json()).access_token;
  const me = await request.get("http://localhost:8001/users/me", { headers: { Authorization: `Bearer ${candidateToken}` } });
  const personId = (await me.json()).id;
  const created = await request.post("http://localhost:8001/zeitarbeit/workers/activate", { headers: { Authorization: `Bearer ${token}` }, data: { user_id: personId } });
  expect(created.ok(), await created.text()).toBeTruthy();
  const errors: string[] = [];
  page.on("pageerror", error => errors.push(error.message));
  await page.goto("/login");
  await page.getByLabel("E-Mail").fill("recruiter@demo-enterprise.de");
  await page.getByLabel("Passwort", { exact: true }).fill("Recruiter1234!");
  await page.getByRole("button", { name: "Anmelden", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Heute", exact: true })).toBeVisible();
  await page.screenshot({ path: "../.artifacts/browser/workspace-today.png", fullPage: true });
  await page.keyboard.press("Control+k");
  const dialog = page.getByRole("dialog", { name: "Globale Suche" });
  await expect(dialog).toBeVisible();
  await dialog.getByRole("textbox").fill("Menschen");
  await dialog.getByRole("link", { name: "Menschen", exact: true }).click();
  await page.getByRole("textbox", { name: "Menschen suchen" }).fill(`Person ${marker}`);
  await page.getByRole("button", { name: "Suchen", exact: true }).click();
  await page.getByRole("button", { name: "Ansicht speichern" }).click();
  await expect(page.getByRole("status").filter({ hasText: "Ansicht in diesem Browser gespeichert" })).toBeVisible();
  await page.getByRole("button", { name: new RegExp(`Person ${marker}`) }).click();
  await expect(page.getByRole("region", { name: "Personenakte" }).getByRole("heading", { name: `Person ${marker}`, exact: true })).toBeVisible();
  await page.reload();
  await expect(page.getByRole("heading", { name: `Person ${marker}`, exact: true })).toBeVisible();
  await page.screenshot({ path: "../.artifacts/browser/workspace-people.png", fullPage: true });
  const axe = await new AxeBuilder({ page }).withTags(["wcag2a", "wcag2aa", "wcag21aa"]).analyze();
  expect(axe.violations.filter(v => ["critical", "serious"].includes(v.impact ?? ""))).toEqual([]);
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390);
  await page.screenshot({ path: "../.artifacts/browser/workspace-people-mobile.png", fullPage: true });
  await page.getByRole("button", { name: "Zur Personenliste" }).click();
  await expect(page.getByRole("button", { name: new RegExp(`Person ${marker}`) })).toBeVisible();
  expect(errors).toEqual([]);
});
