import { test, expect } from "@playwright/test";
import AxeBuilder from "@axe-core/playwright";
import { mkdirSync } from "node:fs";

test("configure an agent, assign a durable task and review its result", async ({ page, request, baseURL }) => {
  test.setTimeout(180_000);
  if (!baseURL || !["localhost", "127.0.0.1"].includes(new URL(baseURL).hostname)) throw new Error("Local synthetic tests only");
  const api = "http://localhost:8001";
  const marker = Date.now();
  const email = `agent-qa-${marker}@example.com`;
  const password = "SyntheticOnly123!";
  // API fixtures: isolated company and draft vacancy. Agent configuration,
  // assignment, review and pause are performed through visible controls.
  const signup = await request.post(`${api}/auth/register`, { data: { email, password, full_name: "Agent QA" } });
  expect(signup.ok(), await signup.text()).toBeTruthy();
  const headers = { Authorization: `Bearer ${(await signup.json()).access_token}` };
  const company = await request.post(`${api}/companies/`, { headers, data: { name: `Agent QA ${marker}`, workspace_type: "internal_hr" } });
  expect(company.ok(), await company.text()).toBeTruthy();
  const vacancy = await request.post(`${api}/jobs/recruiter`, { headers, data: { title: `Agent Teststelle ${marker}`, company: "Synthetic QA", location: "Berlin", description: "Qualitätssicherung unserer Software." } });
  expect(vacancy.ok(), await vacancy.text()).toBeTruthy();
  const errors: string[] = [];
  page.on("pageerror", error => errors.push(error.message));
  await page.goto("/login");
  await page.getByLabel("E-Mail").fill(email);
  await page.getByLabel("Passwort", { exact: true }).fill(password);
  await page.getByRole("button", { name: "Anmelden", exact: true }).click();
  await expect(page).not.toHaveURL(/\/login$/);
  await page.goto("/dashboard/agents");
  await page.getByLabel("Agentenname", { exact: true }).fill("Stellenassistent QA");
  await page.getByRole("combobox", { name: "Verantwortliche Person", exact: true }).selectOption({ label: "Agent QA" });
  await page.getByLabel("Andere Person muss das Ergebnis prüfen", { exact: false }).uncheck();
  await page.getByLabel("Agent für neue Aufgaben aktivieren", { exact: true }).check();
  await page.getByRole("button", { name: "Agent speichern", exact: true }).click();
  await expect(page.getByRole("status")).toHaveText("Agentenkonfiguration gespeichert.");
  await page.reload();
  await page.getByRole("combobox", { name: "Ausführender Agent", exact: true }).selectOption({ label: "Stellenassistent QA" });
  await page.getByRole("combobox", { name: "Stelle für den Auftrag", exact: true }).selectOption({ label: `Agent Teststelle ${marker}` });
  await page.getByLabel("Aufgabentitel", { exact: true }).fill("Stellenangaben vor Veröffentlichung prüfen");
  await page.getByLabel("Hinweise für die Prüfung", { exact: true }).fill("Bitte fehlende Angaben kontrollieren und im Team ergänzen.");
  await page.getByRole("combobox", { name: "Verantwortlich für die Ergebnisprüfung", exact: true }).selectOption({ label: "Agent QA" });
  await page.getByRole("button", { name: "Aufgabe beauftragen", exact: true }).click();
  const run = page.getByRole("region", { name: "Agentenaufträge", exact: true }).getByRole("article").filter({ hasText: "Stellenangaben vor Veröffentlichung prüfen" });
  await expect(run.getByRole("heading")).toContainText("Prüfung erforderlich", { timeout: 60_000 });
  await expect(run).toContainText("Ergebnis aus Regelprüfung");
  await expect(run).toContainText("Fehlende Angaben");
  const captures = "/tmp/hireos-browser-tests/palmscout-agents";
  mkdirSync(captures, { recursive: true });
  await run.scrollIntoViewIfNeeded();
  await page.screenshot({ path: `${captures}/review-desktop.png` });
  await page.setViewportSize({ width: 390, height: 844 });
  await run.getByLabel("Prüfvermerk", { exact: true }).fill("Stellenangaben geprüft; fehlende Anforderungen werden vor Veröffentlichung ergänzt.");
  await run.getByRole("button", { name: "Ergebnis freigeben", exact: true }).click();
  await expect(run.getByRole("heading")).toContainText("Freigegeben");
  await page.reload();
  await expect(run.getByRole("heading")).toContainText("Freigegeben");
  await run.getByText("Eingabestand und Verlauf", { exact: true }).click();
  await expect(run.getByRole("list", { name: "Auftragsverlauf" }).getByRole("listitem")).toHaveCount(3);
  await expect(run).toContainText("Qualitätssicherung unserer Software.");
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390);
  const a11y = await new AxeBuilder({ page }).withTags(["wcag2a", "wcag2aa", "wcag21aa"]).analyze();
  expect(a11y.violations.filter(item => ["serious", "critical"].includes(item.impact ?? ""))).toEqual([]);
  await run.locator("details").screenshot({ path: `${captures}/history-mobile.png` });
  await run.getByText("Eingabestand und Verlauf", { exact: true }).click();
  await run.scrollIntoViewIfNeeded();
  await page.screenshot({ path: `${captures}/approved-mobile.png` });
  await page.getByRole("region", { name: "Agentenverzeichnis", exact: true }).getByRole("button", { name: "Pausieren", exact: true }).click();
  await expect(page.getByRole("region", { name: "Agentenverzeichnis", exact: true })).toContainText("Pausiert");
  await page.getByRole("link", { name: "Gemeinsame Aufgabenübersicht", exact: true }).click();
  const task = page.getByRole("row").filter({ hasText: "Stellenangaben vor Veröffentlichung prüfen" });
  await expect(task).toContainText("Agent: Stellenassistent QA");
  await expect(task.getByRole("button", { name: "Aufgabenstatus ändern", exact: true })).toBeDisabled();
  expect((await request.get(`${api}/jobs/recruiter/${(await vacancy.json()).id}`, { headers })).ok()).toBeTruthy();
  const job = await (await request.get(`${api}/jobs/recruiter/${(await vacancy.json()).id}`, { headers })).json();
  expect(job.publication_status).toBe("draft");
  expect(errors).toEqual([]);
});
